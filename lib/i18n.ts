const cutTranslations: Record<Exclude<Locale, "es">, CutTranslationData> = {
  en: cutsEnglish,
  pt: cutsPortuguese
};

export function translateCorte<T extends Corte>(corte: T, locale: Locale): T {
  if (locale === "es") return corte;
  const translated = cutTranslations[locale][corte.slug];
  if (!translated) return corte;
  const usos = "usos" in corte
    ? (corte as CorteDetalle).usos.map((uso, index) => ({
        ...uso,
        titulo: translated.usos[index]?.titulo ?? uso.titulo,
        detalle: translated.usos[index]?.detalle ?? uso.detalle
      }))
    : undefined;
  return {
    ...corte,
    nombre: translated.nombre,
    descripcion: translated.descripcion,
    textura: translated.textura,
    coccion: translated.coccion,
    ...(usos ? { usos } : {})
  };
}
